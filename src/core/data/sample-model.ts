/**
 * Semantic model of the built-in sample project: a sales star schema
 *
 *   Sales (fact) ──many:1──▶ Date      (marked as date table)
 *                ──many:1──▶ Product   (Category ▸ Subcategory ▸ Product)
 *                ──many:1──▶ Store
 *                ──many:1──▶ Customer ──many:1──▶ Region   (snowflake)
 *
 * plus a `_Measures` table holding the report measures (display folders, format strings).
 * Store carries its city/country as plain attributes: relating it to Region as well would create
 * two active filter paths from Sales to Region, which Power BI rejects as ambiguous.
 *
 * Partitions are Power Query M. Small dimensions embed their rows (`#table(..., {rows})`) and the
 * Date table computes the calendar, so those queries reproduce the loaded data exactly. Sales and
 * Customer are too large to embed: their query only declares the schema and documents that rows
 * come from the in-app generator. Every table (and the model) carries the annotation
 * `Lumen_Sample = true` so refresh orchestration can tell the data is not refreshable.
 */

const sampleAnnotations = (): Annotations => ({ [SAMPLE_ANNOTATION]: 'true' })

function buildTable(name: string, t: SampleTableRows): TableDef {
  const meta = COLUMN_META[name] ?? {}
  const columns: ColumnDef[] = t.columns.map((c) => {
    const m = meta[c.name] ?? {}
    return {
      name: c.name,
      dataType: c.type,
      kind: 'data',
      sourceColumn: c.name,
      summarizeBy: m.summarizeBy ?? (c.type === 'string' || c.type === 'boolean' || c.type === 'dateTime' ? 'none' : 'sum'),
      lineageTag: stableUuid(`column:${name}.${c.name}`),
      ...m
    }
  })
  const hierarchies: HierarchyDef[] = (HIERARCHIES[name] ?? []).map((h) => ({
    name: h.name,
    lineageTag: stableUuid(`hierarchy:${name}.${h.name}`),
    levels: h.levels.map((col, ordinal) => ({ name: col, column: col, ordinal, lineageTag: stableUuid(`level:${name}.${h.name}.${col}`) }))
  }))
  return {
    name,
    columns,
    measures: [],
    hierarchies,
    partitions: [partitionFor(name, t)],
    ...(name === 'Date' ? { dataCategory: 'Time' } : {}),
    description: TABLE_DESCRIPTIONS[name],
    lineageTag: stableUuid(`table:${name}`),
    annotations: sampleAnnotations()
  }
}

/** Rows of the measure table (an "Enter data"-style table with one hidden column and no rows). */
export const MEASURE_TABLE_ROWS: SampleTableRows = { columns: [{ name: 'Column1', type: 'string' }], rows: [] }

function buildMeasureTable(): TableDef {
  const measures: MeasureDef[] = SAMPLE_MEASURES.map((m) => ({
    name: m.name,
    expression: m.expression,
    formatString: m.formatString,
    displayFolder: m.displayFolder,
    description: m.description,
    lineageTag: stableUuid(`measure:${m.name}`)
  }))
  return {
    name: MEASURE_TABLE,
    columns: [
      { name: 'Column1', dataType: 'string', kind: 'data', sourceColumn: 'Column1', isHidden: true, summarizeBy: 'none', lineageTag: stableUuid('column:_Measures.Column1') }
    ],
    measures,
    hierarchies: [],
    partitions: [
      {
        name: `${MEASURE_TABLE}-${stableUuid('partition:_Measures').slice(0, 8)}`,
        mode: 'import',
        sourceType: 'm',
        expression: 'let\n    // Measure table: holds the report measures, no data.\n    Source = #table(type table [Column1 = text], {})\nin\n    Source'
      }
    ],
    description: TABLE_DESCRIPTIONS[MEASURE_TABLE],
    lineageTag: stableUuid(`table:${MEASURE_TABLE}`),
    annotations: sampleAnnotations()
  }
}

function rel(fromTable: string, fromColumn: string, toTable: string, toColumn: string): RelationshipDef {
  return {
    name: stableUuid(`relationship:${fromTable}.${fromColumn}->${toTable}.${toColumn}`),
    fromTable,
    fromColumn,
    toTable,
    toColumn,
    fromCardinality: 'many',
    toCardinality: 'one',
    crossFilteringBehavior: 'oneDirection',
    isActive: true
  }
}

export const SAMPLE_TABLE_ORDER = ['Sales', 'Date', 'Product', 'Customer', 'Region', 'Store'] as const

export function buildSampleModel(rows: SampleRows): SemanticModel {
  const tables = [buildMeasureTable(), ...SAMPLE_TABLE_ORDER.map((n) => buildTable(n, rows[n]))]
  return {
    name: 'Sample - Sales',
    culture: 'en-US',
    compatibilityLevel: 1600,
    defaultPowerBIDataSourceVersion: 'powerBI_V3',
    sourceQueryCulture: 'en-US',
    tables,
    relationships: [
      rel('Sales', 'OrderDate', 'Date', 'Date'),
      rel('Sales', 'ProductKey', 'Product', 'ProductKey'),
      rel('Sales', 'CustomerKey', 'Customer', 'CustomerKey'),
      rel('Sales', 'StoreKey', 'Store', 'StoreKey'),
      rel('Customer', 'RegionKey', 'Region', 'RegionKey')
    ],
    expressions: [],
    roles: [],
    annotations: {
      ...sampleAnnotations(),
      // Auto date/time off: the model has its own date table.
      __PBI_TimeIntelligenceEnabled: '0',
      PBI_QueryOrder: JSON.stringify([MEASURE_TABLE, ...SAMPLE_TABLE_ORDER])
    }
  }
}

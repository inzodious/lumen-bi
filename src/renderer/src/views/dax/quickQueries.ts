/**
 * DAX query view "Quick queries" (Data pane context menu), generated like Power BI Desktop does
 * (tabs for indentation, a leading comment naming the quick query).
 */
import type { SemanticModel, TableDef } from '@core/model/types'
import { quoteColumn, quoteTable, tokenizeDax, unquoteRef } from '../../editors/dax/tokenizer'

const T = '\t'
const col = (t: string, c: string) => `${quoteTable(t)}${quoteColumn(c)}`
const str = (s: string) => `"${s.replace(/"/g, '""')}"`

export function topRowsQuery(table: string, n = 100): string {
  return `// DAX query generated by "Show top ${n} rows"\nEVALUATE\n${T}TOPN(${n}, ${quoteTable(table)})`
}

export function columnPreviewQuery(table: string, column: string, n = 100): string {
  return `// DAX query generated by "Show data preview"\nEVALUATE\n${T}TOPN(${n}, VALUES(${col(table, column)}))`
}

function statsRow(t: TableDef, c: TableDef['columns'][number]): string {
  const ref = col(t.name, c.name)
  const isText = c.dataType === 'string'
  const lines = [
    `"Table Name", ${str(t.name)}`,
    `"Column Name", ${str(c.name)}`,
    `"Min", "" & MIN(${ref})`,
    `"Max", "" & MAX(${ref})`,
    `"Cardinality", DISTINCTCOUNT(${ref})`,
    `"Max Length", ${isText ? `MAXX(VALUES(${ref}), LEN(${ref}))` : 'BLANK()'}`
  ]
  return `ROW(\n${lines.map((l) => T + T + T + l).join(',\n')}\n${T}${T})`
}

/** Column statistics for one column, or for every (non-binary) column of the table. */
export function columnStatisticsQuery(model: SemanticModel, table: string, column?: string): string {
  const t = model.tables.find((x) => x.name === table)
  if (!t) return ''
  const cols = t.columns.filter((c) => c.kind !== 'rowNumber' && c.dataType !== 'binary' && (!column || c.name === column))
  const rows = cols.map((c) => statsRow(t, c))
  const body = rows.length === 1 ? `${T}${rows[0].replace(/\n\t\t/g, '\n\t')}` : `${T}UNION(\n${rows.map((r) => T + T + r.replace(/\n/g, '\n' + T)).join(',\n')}\n${T})`
  return `// DAX query generated by "Show column statistics"\nEVALUATE\n${body}`
}

/** Names of measures referenced (directly) by an expression. */
export function referencedMeasures(model: SemanticModel, expression: string): string[] {
  const names = new Set(model.tables.flatMap((t) => t.measures.map((m) => m.name.toLowerCase())))
  const out: string[] = []
  const toks = tokenizeDax(expression)
  for (let i = 0; i < toks.length; i++) {
    const tk = toks[i]
    if (tk.type !== 'column') continue
    const prev = toks[i - 1]
    if (prev && (prev.type === 'table' || prev.type === 'ident')) {
      // Table[Measure] is legal too
      const n = unquoteRef(tk.text)
      if (names.has(n.toLowerCase()) && !out.includes(n)) out.push(n)
      continue
    }
    const n = unquoteRef(tk.text)
    if (names.has(n.toLowerCase()) && !out.some((x) => x.toLowerCase() === n.toLowerCase())) out.push(n)
  }
  return out
}

function measureDef(model: SemanticModel, name: string): { table: string; expression: string } | null {
  for (const t of model.tables) {
    const m = t.measures.find((x) => x.name.toLowerCase() === name.toLowerCase())
    if (m) return { table: t.name, expression: m.expression }
  }
  return null
}

/** Measure plus its (transitive) measure dependencies, dependencies first. */
export function measureClosure(model: SemanticModel, names: string[]): string[] {
  const out: string[] = []
  const visiting = new Set<string>()
  const visit = (n: string) => {
    const key = n.toLowerCase()
    if (out.some((x) => x.toLowerCase() === key) || visiting.has(key)) return
    visiting.add(key)
    const def = measureDef(model, n)
    if (def) for (const r of referencedMeasures(model, def.expression)) visit(r)
    visiting.delete(key)
    if (def) out.push(model.tables.flatMap((t) => t.measures).find((m) => m.name.toLowerCase() === key)!.name)
  }
  for (const n of names) visit(n)
  return out
}

function defineBlock(model: SemanticModel, names: string[]): string {
  const lines = names.map((n) => {
    const d = measureDef(model, n)!
    const expr = d.expression.trim()
    const body = expr.includes('\n') ? `\n${expr.split('\n').map((l) => T + T + l).join('\n')}` : ` ${expr}`
    return `${T}MEASURE ${col(d.table, n)} =${body}`
  })
  return `DEFINE\n${lines.join('\n')}\n`
}

function evaluateMeasures(names: string[]): string {
  return `EVALUATE\n${T}SUMMARIZECOLUMNS(\n${names.map((n) => `${T}${T}${str(n)}, ${quoteColumn(n)}`).join(',\n')}\n${T})`
}

export function evaluateMeasureQuery(model: SemanticModel, measure: string, mode: 'evaluate' | 'define' | 'defineWithReferences' = 'evaluate'): string {
  const header = mode === 'evaluate' ? '// DAX query generated by "Evaluate"' : mode === 'define' ? '// DAX query generated by "Define and evaluate"' : '// DAX query generated by "Define with references and evaluate"'
  const defs = mode === 'evaluate' ? [] : mode === 'define' ? [measure] : measureClosure(model, [measure])
  return `${header}\n${defs.length ? defineBlock(model, defs) + '\n' : ''}${evaluateMeasures([measure])}`
}

export function defineAllMeasuresQuery(model: SemanticModel, table: string, withReferences = false): string {
  const t = model.tables.find((x) => x.name === table)
  const names = t?.measures.map((m) => m.name) ?? []
  if (!names.length) return `// The table ${table} has no measures.`
  const defs = withReferences ? measureClosure(model, names) : names
  const header = withReferences ? '// DAX query generated by "Define all measures in this table and references"' : '// DAX query generated by "Define all measures in this table"'
  return `${header}\n${defineBlock(model, defs)}\n${evaluateMeasures(names)}`
}

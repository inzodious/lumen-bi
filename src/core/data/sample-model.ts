const M_TYPES: Partial<Record<DataType, string>> = {
  int64: 'Int64.Type',
  decimal: 'Currency.Type',
  double: 'type number',
  string: 'type text',
  dateTime: 'type date',
  boolean: 'type logical'
}

function mName(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : `#"${name.replace(/"/g, '""')}"`
}

function mLiteral(v: Scalar): string {
  if (v === null) return 'null'
  if (typeof v === 'string') return `"${v.replace(/"/g, '""')}"`
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (v instanceof Date) return `#date(${v.getUTCFullYear()}, ${v.getUTCMonth() + 1}, ${v.getUTCDate()})`
  return 'null'
}

function mTableType(t: SampleTableRows): string {
  return `type table [${t.columns.map((c) => `${mName(c.name)} = ${(M_TYPES[c.type] ?? 'type any').replace(/^type /, '')}`).join(', ')}]`
}

/** `#table` with the rows embedded — used for the small dimension tables. */
function embeddedTableM(t: SampleTableRows): string {
  const rows = t.rows.map((r) => `        {${r.map(mLiteral).join(', ')}}`).join(',\n')
  return [
    'let',
    '    // Sample data (Lumen built-in sample project), entered as a table literal.',
    `    Source = #table(\n        ${mTableType(t)},\n        {\n${rows}\n        }\n    )`,
    'in',
    '    Source'
  ].join('\n')
}

/** Schema-only query for the generated tables (Sales, Customer). */
function generatedTableM(t: SampleTableRows): string {
  return [
    'let',
    '    // Sample data (Lumen built-in sample project). The rows of this table are generated',
    '    // in-app from a fixed seed and saved with the project; this query only declares the',
    '    // schema, so refreshing it would return an empty table. The table is annotated',
    `    // ${SAMPLE_ANNOTATION} = true so refresh leaves it alone.`,
    `    Source = #table(${mTableType(t)}, {})`,
    'in',
    '    Source'
  ].join('\n')
}

/** The calendar computed in M — evaluates to exactly the generated Date rows. */
export function dateTableM(): string {
  return `let
    // Sample calendar (Lumen built-in sample project): one row per day.
    StartDate = #date(${SAMPLE_START_YEAR}, 1, 1),
    EndDate = #date(${SAMPLE_END_YEAR}, 12, 31),
    Dates = List.Dates(StartDate, Duration.Days(EndDate - StartDate) + 1, #duration(1, 0, 0, 0)),
    Source = #table(type table [Date = date], List.Transform(Dates, each {_})),
    AddYear = Table.AddColumn(Source, "Year", each Date.Year([Date]), Int64.Type),
    AddQuarter = Table.AddColumn(AddYear, "Quarter", each "Q" & Text.From(Date.QuarterOfYear([Date])), type text),
    AddMonthNumber = Table.AddColumn(AddQuarter, "Month Number", each Date.Month([Date]), Int64.Type),
    AddMonth = Table.AddColumn(AddMonthNumber, "Month", each Date.MonthName([Date]), type text),
    AddMonthShort = Table.AddColumn(AddMonth, "Month Short", each Text.Start([Month], 3), type text),
    AddYearMonth = Table.AddColumn(AddMonthShort, "Year Month", each [Month Short] & " " & Text.From([Year]), type text),
    AddYearMonthNumber = Table.AddColumn(AddYearMonth, "Year Month Number", each [Year] * 100 + [Month Number], Int64.Type),
    // Weeks start on Monday; week 1 contains January 1 (same as Date.WeekOfYear([Date], Day.Monday)).
    AddWeek = Table.AddColumn(AddYearMonthNumber, "Week of Year", each Number.RoundDown((Date.DayOfYear([Date]) - 1 + Date.DayOfWeek(Date.StartOfYear([Date]), Day.Monday)) / 7) + 1, Int64.Type),
    AddDayOfWeek = Table.AddColumn(AddWeek, "Day of Week", each Date.DayOfWeekName([Date]), type text),
    AddDayOfWeekNumber = Table.AddColumn(AddDayOfWeek, "Day of Week Number", each Date.DayOfWeek([Date], Day.Monday) + 1, Int64.Type),
    AddIsWeekend = Table.AddColumn(AddDayOfWeekNumber, "Is Weekend", each [Day of Week Number] >= 6, type logical)
in
    AddIsWeekend`
}

const EMBED_MAX_ROWS = 200

function partitionFor(name: string, t: SampleTableRows): PartitionDef {
  const expression = name === 'Date' ? dateTableM() : t.rows.length <= EMBED_MAX_ROWS ? embeddedTableM(t) : generatedTableM(t)
  return { name: `${name}-${stableUuid(`partition:${name}`).slice(0, 8)}`, mode: 'import', sourceType: 'm', expression }
}


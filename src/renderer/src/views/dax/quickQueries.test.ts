import { describe, expect, it } from 'vitest'
import { emptyModel, type SemanticModel } from '@core/model/types'
import { columnPreviewQuery, columnStatisticsQuery, defineAllMeasuresQuery, evaluateMeasureQuery, measureClosure, referencedMeasures, topRowsQuery } from './quickQueries'
import { localDaxDiagnostics } from '../../editors/dax/diagnostics'
import { schemaFromModel } from '../../editors/dax/schema'
import { isDaxQueryText } from '../../editors/dax/formatter'

function model(): SemanticModel {
  const m = emptyModel()
  m.tables = [
    {
      name: 'Sales Fact',
      columns: [
        { name: 'Amount', dataType: 'double', kind: 'data' },
        { name: 'Region', dataType: 'string', kind: 'data' }
      ],
      measures: [
        { name: 'Total', expression: "SUM('Sales Fact'[Amount])" },
        { name: 'Double', expression: '[Total] * 2' },
        { name: 'Quad', expression: 'VAR x = [Double]\nRETURN\n    x * 2' }
      ],
      hierarchies: [],
      partitions: []
    }
  ]
  return m
}

const clean = (q: string, m: SemanticModel) => localDaxDiagnostics(q, schemaFromModel(m)).filter((d) => d.severity === 'error')

describe('quick queries', () => {
  it('top rows / preview', () => {
    expect(topRowsQuery('Sales Fact')).toBe(`// DAX query generated by "Show top 100 rows"\nEVALUATE\n\tTOPN(100, 'Sales Fact')`)
    expect(columnPreviewQuery('Sales Fact', 'Region')).toContain("VALUES('Sales Fact'[Region])")
  })
  it('column statistics are valid queries', () => {
    const m = model()
    const all = columnStatisticsQuery(m, 'Sales Fact')
    expect(all).toContain('UNION(')
    expect(all).toContain("MAXX(VALUES('Sales Fact'[Region]), LEN('Sales Fact'[Region]))")
    expect(clean(all, m)).toEqual([])
    const one = columnStatisticsQuery(m, 'Sales Fact', 'Amount')
    expect(one).not.toContain('UNION(')
    expect(clean(one, m)).toEqual([])
    expect(isDaxQueryText(one)).toBe(true)
  })
  it('finds measure references and closures', () => {
    const m = model()
    expect(referencedMeasures(m, "[Total] + 'Sales Fact'[Double] + 'Sales Fact'[Amount]")).toEqual(['Total', 'Double'])
    expect(measureClosure(m, ['Quad'])).toEqual(['Total', 'Double', 'Quad'])
  })
  it('defines and evaluates measures', () => {
    const m = model()
    const q = evaluateMeasureQuery(m, 'Quad', 'defineWithReferences')
    expect(q).toContain("MEASURE 'Sales Fact'[Total] = SUM('Sales Fact'[Amount])")
    expect(q).toContain("MEASURE 'Sales Fact'[Quad] =\n\t\tVAR x = [Double]")
    expect(q.indexOf('[Total] =')).toBeLessThan(q.indexOf('[Quad] ='))
    expect(clean(q, m)).toEqual([])
    expect(evaluateMeasureQuery(m, 'Total')).toBe(`// DAX query generated by "Evaluate"\nEVALUATE\n\tSUMMARIZECOLUMNS(\n\t\t"Total", [Total]\n\t)`)
    const all = defineAllMeasuresQuery(m, 'Sales Fact')
    expect(all.match(/MEASURE/g)).toHaveLength(3)
    expect(clean(all, m)).toEqual([])
  })
})

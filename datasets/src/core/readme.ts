/**
 * Renders the per-universe README.md: premise, layout, Mermaid ER diagram, table catalog with row
 * counts, bronze sources, planted data-quality issues, semantic-model measures and analysis ideas.
 */
import type { SemanticModel } from '../../../src/core/model/types.ts'
import { isoDate } from './calendar.ts'
import { CALC_GROUP_TABLE, MEASURES_TABLE } from './semantic/model.ts'
import { modelColumnName } from './schema.ts'
import type { TableSpec, Universe } from './schema.ts'

export interface ReadmeStats {
  scale: string
  seed: number
  today: Date
  /** first day of history */
  start: Date
  rows: Map<string, number>
  /** bytes on disk per table (Parquet + log), optional */
  bytes?: Map<string, number>
  bronze: Map<string, { files: number; rows: number }>
  issues: Map<string, number>
  model: SemanticModel
  /** relative link to datasets/README.md from where this README is written */
  rootLink?: string
}

function n(v: number): string {
  return v.toLocaleString('en-US')
}

function md(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function bytes(b: number): string {
  if (b < 1024) return `${b} B`
  if (b < 1024 * 1024) return `${(b / 1024).toFixed(1)} KB`
  return `${(b / 1024 / 1024).toFixed(1)} MB`
}

function kindLabel(s: TableSpec): string {
  if (s.kind === 'fact') return `fact (${s.factType ?? 'transaction'})`
  return s.scd2 ? 'dim (SCD2)' : s.kind
}

export function mermaidEr(specs: TableSpec[]): string {
  const gold = specs.filter((s) => s.layer === 'gold')
  const names = new Set(gold.map((s) => s.name))
  const lines = ['erDiagram']
  for (const s of gold) {
    for (const fk of s.fks ?? []) {
      if (!names.has(fk.table)) continue
      const card = fk.oneToOne ? '||--||' : '||--o{'
      const tag = [fk.role ?? fk.column, fk.inactive ? 'inactive' : '', fk.bidirectional ? 'both' : ''].filter(Boolean).join(', ')
      lines.push(`    ${fk.table} ${card} ${s.name} : "${tag}"`)
    }
  }
  for (const s of gold) {
    const fkCols = new Set((s.fks ?? []).map((f) => f.column))
    const shown = s.columns.filter((c) => s.key.includes(c.name) || fkCols.has(c.name))
    if (!shown.length) continue
    lines.push(`    ${s.name} {`)
    for (const c of shown) {
      const tags = [s.key.includes(c.name) ? 'PK' : '', fkCols.has(c.name) ? 'FK' : ''].filter(Boolean).join(',')
      lines.push(`        ${c.kind} ${c.name}${tags ? ` ${tags}` : ''}`)
    }
    lines.push('    }')
  }
  return lines.join('\n')
}

function tableSection(s: TableSpec, stats: ReadmeStats): string {
  const out: string[] = []
  out.push(`#### \`${s.name}\`${s.model ? ` → model table **${s.model.name}**` : ''}`)
  out.push('')
  out.push(s.description)
  out.push('')
  out.push(`- **Type:** ${kindLabel(s)} · **Grain:** ${s.grain}`)
  out.push(`- **Key:** ${s.key.map((k) => `\`${k}\``).join(', ')} · **Rows:** ${n(stats.rows.get(s.name) ?? 0)}${stats.bytes?.has(s.name) ? ` · **Size:** ${bytes(stats.bytes.get(s.name)!)}` : ''}`)
  if (s.fks?.length) out.push(`- **Foreign keys:** ${s.fks.map((f) => `\`${f.column}\` → \`${f.table}\`${f.inactive ? ' (inactive)' : ''}${f.bidirectional ? ' (bidirectional)' : ''}`).join(', ')}`)
  if (s.partitionByYearOf) out.push(`- **Partitioned by:** \`year\` (year of \`${s.partitionByYearOf}\`)`)
  if (s.scd2) out.push(`- **SCD Type 2:** business key \`${s.scd2.businessKey}\`, validity \`${s.scd2.from}\` … \`${s.scd2.to}\`, current flag \`${s.scd2.current}\``)
  out.push('')
  out.push('<details><summary>Columns</summary>')
  out.push('')
  out.push(`| Column | Type | ${s.model ? 'Model name | ' : ''}Description |`)
  out.push(`|---|---|${s.model ? '---|' : ''}---|`)
  for (const c of s.columns) {
    out.push(`| \`${c.name}\` | ${c.kind} | ${s.model ? (c.exclude ? '—' : md(modelColumnName(c))) + ' | ' : ''}${md(c.description)} |`)
  }
  out.push('')
  out.push('</details>')
  return out.join('\n')
}

export function renderUniverseReadme(u: Universe, specs: TableSpec[], stats: ReadmeStats): string {
  const gold = specs.filter((s) => s.layer === 'gold')
  const silver = specs.filter((s) => s.layer === 'silver')
  const facts = gold.filter((s) => s.kind === 'fact')
  const dims = gold.filter((s) => s.kind === 'dim')
  const sum = (list: TableSpec[]) => list.reduce((t, s) => t + (stats.rows.get(s.name) ?? 0), 0)
  const bronzeFiles = [...stats.bronze.values()].reduce((t, b) => t + b.files, 0)
  const measures = stats.model.tables.find((t) => t.name === MEASURES_TABLE)?.measures ?? []
  const cg = stats.model.tables.find((t) => t.name === CALC_GROUP_TABLE)?.calculationGroup
  const out: string[] = []

  out.push(`# ${u.company} — \`${u.name}.Lakehouse\``)
  out.push('')
  out.push(`> ${u.tagline}`)
  out.push('')
  out.push(`*A fictional dataset generated by the Lumen dataset generator — every company, person, place and number here is made up.*`)
  out.push('')
  out.push('## The story')
  out.push('')
  out.push(u.premise.trim())
  out.push('')
  out.push('## At a glance')
  out.push('')
  out.push('| | |')
  out.push('|---|---|')
  out.push(`| Analytic shapes | ${u.shapes.join(' · ')} |`)
  out.push(`| Gold star schema | ${facts.length} facts, ${dims.length} dimensions${bridgeText(gold.filter((s) => s.kind === 'bridge').length)} (${n(sum(gold))} rows) |`)
  out.push(`| Silver | ${silver.length} conformed tables (${n(sum(silver))} rows) |`)
  out.push(`| Bronze | ${stats.bronze.size} sources, ${n(bronzeFiles)} raw files, ${u.issues.length} planted data-quality issues |`)
  out.push(`| Semantic model | ${stats.model.tables.length} tables, ${stats.model.relationships.length} relationships, ${measures.length} measures, ${cg?.items.length ?? 0} time-intelligence items |`)
  out.push(`| History | ${isoDate(stats.start)} … ${isoDate(stats.today)} · fiscal year starts in month ${u.fiscalYearStartMonth} |`)
  out.push(`| This build | scale \`${stats.scale}\`, seed \`${stats.seed}\` (same seed ⇒ byte-identical output) |`)
  out.push('')
  out.push('## Layout')
  out.push('')
  out.push('```text')
  out.push(`${u.id}/`)
  out.push(`├── ${u.name}.Lakehouse/`)
  out.push('│   ├── Files/bronze/        raw landing files (CSV / JSON / NDJSON / XLSX) with planted issues')
  out.push('│   └── Tables/              Delta tables: silver_* (cleaned) and gold_* (star schema)')
  out.push(`├── ${u.name}.SemanticModel/  TMDL semantic model (import mode, reads gold Parquet)`)
  out.push(`├── ${u.name}.Report/         PBIR starter report`)
  out.push(`├── ${u.name}.pbip            open this in Power BI Desktop or Lumen`)
  out.push('├── csv/                     plain CSV export of every silver/gold table (with --formats csv)')
  out.push('└── README.md')
  out.push('```')
  out.push('')
  out.push('## Gold star schema')
  out.push('')
  out.push('```mermaid')
  out.push(mermaidEr(specs))
  out.push('```')
  out.push('')
  out.push('## Table catalog')
  out.push('')
  out.push('| Table | Layer | Type | Grain | Rows |')
  out.push('|---|---|---|---|---:|')
  for (const s of [...gold, ...silver]) out.push(`| \`${s.name}\` | ${s.layer} | ${kindLabel(s)} | ${md(s.grain)} | ${n(stats.rows.get(s.name) ?? 0)} |`)
  out.push('')
  out.push('### Gold')
  out.push('')
  for (const s of gold) out.push(tableSection(s, stats), '')
  out.push('### Silver')
  out.push('')
  for (const s of silver) out.push(tableSection(s, stats), '')
  out.push('## Bronze sources')
  out.push('')
  out.push('| Source | Upstream system | Format | Path pattern | Cadence | Files | Rows |')
  out.push('|---|---|---|---|---|---:|---:|')
  for (const s of u.sources) {
    const b = stats.bronze.get(s.id) ?? { files: 0, rows: 0 }
    out.push(`| \`${s.id}\` | ${md(s.system)} | ${s.format} | \`${s.pattern}\` | ${md(s.cadence)} | ${n(b.files)} | ${n(b.rows)} |`)
  }
  out.push('')
  for (const s of u.sources) out.push(`- **${s.id}** — ${s.description}`)
  out.push('')
  out.push('## Planted data-quality issues (bronze)')
  out.push('')
  out.push('Bronze is deliberately messy so you can practise Power Query / Spark cleaning. Silver shows the cleaned result.')
  out.push('')
  out.push('| Code | Source | Column | Issue | Planted | How silver fixes it |')
  out.push('|---|---|---|---|---:|---|')
  for (const i of u.issues) {
    out.push(`| ${i.code} | \`${i.source}\` | ${i.column ? `\`${i.column}\`` : '—'} | **${i.kind.replace(/_/g, ' ')}** — ${md(i.description)} | ${n(stats.issues.get(i.code) ?? 0)} | ${md(i.fix)} |`)
  }
  out.push('')
  out.push('## Semantic model')
  out.push('')
  out.push(`\`${u.name}.SemanticModel\` is an import-mode model over the gold tables. Each table's partition reads its Parquet file(s) through the \`LakehousePath\` parameter (\`expressions.tmdl\`) — set it to the absolute path of \`${u.name}.Lakehouse\` on your machine.`)
  out.push('')
  out.push('- Model tables: ' + stats.model.tables.map((t) => `**${t.name}**`).join(', '))
  const inactive = stats.model.relationships.filter((r) => !r.isActive)
  const both = stats.model.relationships.filter((r) => r.crossFilteringBehavior === 'bothDirections')
  if (inactive.length) out.push(`- Inactive (role-playing) relationships: ${inactive.map((r) => `${r.fromTable}[${r.fromColumn}] → ${r.toTable}[${r.toColumn}]`).join('; ')} — activate with \`USERELATIONSHIP\`.`)
  if (both.length) out.push(`- Bidirectional relationships: ${both.map((r) => `${r.fromTable}[${r.fromColumn}] ↔ ${r.toTable}[${r.toColumn}]`).join('; ')}.`)
  if (cg) out.push(`- Calculation group **${CALC_GROUP_TABLE}**: ${cg.items.map((i) => i.name).join(', ')}.`)
  if (u.fieldParameter) out.push(`- Field parameter **${u.fieldParameter.name}**: ${u.fieldParameter.fields.map((f) => f.label).join(', ')}.`)
  out.push('')
  out.push('### Measures')
  out.push('')
  out.push('| Folder | Measure | Format | What it means |')
  out.push('|---|---|---|---|')
  for (const m of measures) out.push(`| ${m.displayFolder ?? ''} | **${md(m.name)}** | ${m.formatStringDefinition ? 'dynamic' : `\`${md(m.formatString ?? '')}\``} | ${md(m.description ?? '')} |`)
  out.push('')
  out.push('## Suggested analyses')
  out.push('')
  u.analyses.forEach((a, i) => {
    out.push(`${i + 1}. **${a.title}** — ${a.question} *How:* ${a.how}`)
  })
  out.push('')
  if (u.notes) {
    out.push(u.notes.trim())
    out.push('')
  }
  out.push('## Regenerate')
  out.push('')
  out.push('```bash')
  out.push(`node datasets/src/node/cli.ts generate ${u.id} --scale ${stats.scale} --seed ${stats.seed} --today ${isoDate(stats.today)}`)
  out.push('```')
  out.push('')
  out.push(`See [the datasets README](${stats.rootLink ?? '../README.md'}) for loading into Lumen, Power BI Desktop, Fabric, DuckDB and Spark.`)
  out.push('')
  return out.join('\n')
}

function bridgeText(n: number): string {
  return n === 0 ? '' : n === 1 ? ', 1 bridge' : `, ${n} bridges`
}

#!/usr/bin/env node
/**
 * Regenerate src/renderer/src/icons/sets/fluentColor.generated.ts: a barrel of the `*Color` components of
 * @fluentui/react-icons (the unsized ones, drawn on the 20 px grid), imported from the package's per-icon atom modules
 * (`@fluentui/react-icons/svg/<atom>`), so the lazily loaded Fluent Color chunk holds only those components and the
 * picker never imports the whole library.
 *
 * Run after upgrading @fluentui/react-icons:  node scripts/icons/gen-fluent-color.mjs
 * (src/renderer/src/icons/registry.test.ts fails while the file is out of date.)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

/** `{ atom, name }` for every unsized `<Name>Color` component of the installed package, sorted by name. */
export function fluentColorComponents() {
  const require = createRequire(join(root, 'package.json'))
  const pkgDir = dirname(require.resolve('@fluentui/react-icons/package.json'))
  const dir = join(pkgDir, 'lib', 'atoms', 'svg')
  const out = []
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.js')) continue
    const src = readFileSync(join(dir, f), 'utf8')
    for (const m of src.matchAll(/export const ([A-Za-z]+Color) = /g)) if (!/\dColor$/.test(m[1])) out.push({ atom: f.replace(/\.js$/, ''), name: m[1] })
  }
  return out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
}

export function fluentColorBarrel() {
  const lines = fluentColorComponents().map((c) => `export { ${c.name} } from '@fluentui/react-icons/svg/${c.atom}'`)
  return `// Generated by scripts/icons/gen-fluent-color.mjs — do not edit.
// The Fluent Color icon set: the unsized \`*Color\` components of @fluentui/react-icons (${lines.length} icons, 20 px grid).
${lines.join('\n')}
`
}

export const BARREL_PATH = join(root, 'src', 'renderer', 'src', 'icons', 'sets', 'fluentColor.generated.ts')

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(BARREL_PATH, fluentColorBarrel())
  console.log(`wrote ${BARREL_PATH}`)
}
